// The demo page has to open from a double click, and browsers refuse to load ES modules
// over file://. So the engine is inlined into index.html between two markers.
//
// It is still one engine, not a copy maintained by hand: this script does the inlining,
// and tests/engine-parity.test.js fails if index.html ever drifts from the files.
//
//   npm run build:demo

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

/** Dependency order - each file may only use what is already above it. */
export const SOURCES = [
  'engine/catalog.js',
  'engine/format.js',
  'engine/slots.js',
  'engine/validate.js',
  'engine/pricing.js',
  'engine/orders.js',
  'engine/text.js',
  'engine/dialog.js',
  'engine/harness.js',
  'demo/scenarios.js',
];

export const START = '// ---- ENGINE:START (generated by demo/build-embedded.js - do not edit by hand) ----';
export const END = '// ---- ENGINE:END ----';

export function buildEngineBundle(root = ROOT) {
  const parts = [];
  const declared = new Map();

  for (const relative of SOURCES) {
    const source = readFileSync(resolve(root, relative), 'utf8');
    const stripped = strip(source);
    for (const name of topLevelNames(stripped)) {
      if (declared.has(name)) {
        throw new Error(`Name collision: "${name}" is declared in both ${declared.get(name)} and ${relative}. Rename one of them.`);
      }
      declared.set(name, relative);
    }
    parts.push(`// ---- ${relative} ----`, stripped.trim(), '');

    // dialog.js reaches for the texts as T.*; the modules keep that readable,
    // the bundle needs the namespace rebuilt once text.js is in scope.
    if (relative === 'engine/text.js') {
      parts.push(`const T = { ${exportedNames(source).join(', ')} };`, '');
    }
  }

  return parts.join('\n').trim();
}

export function render(root = ROOT) {
  const htmlPath = resolve(root, 'demo/index.html');
  const html = readFileSync(htmlPath, 'utf8');
  const bundle = buildEngineBundle(root);
  const startAt = html.indexOf(START);
  const endAt = html.indexOf(END);
  if (startAt < 0 || endAt < 0) throw new Error('Markers ENGINE:START / ENGINE:END not found in demo/index.html');
  const next = `${html.slice(0, startAt)}${START}\n${bundle}\n${END}${html.slice(endAt + END.length)}`;
  return { htmlPath, html: next, changed: next !== html, bundle };
}

/** The bundle as index.html should contain it, for the parity test. */
export function embeddedFromHtml(html) {
  const startAt = html.indexOf(START);
  const endAt = html.indexOf(END);
  if (startAt < 0 || endAt < 0) return null;
  return html.slice(startAt + START.length, endAt).trim();
}

function strip(source) {
  return source
    .replace(/^import\s[\s\S]*?;\s*$/gm, '')      // import { a } from './b.js';
    .replace(/^export\s*\{[^}]*\}\s*;\s*$/gm, '') // export { a, b };
    .replace(/^export\s+(?=(const|let|var|function|class|async))/gm, '');
}

function exportedNames(source) {
  const names = [];
  const direct = source.matchAll(/^export\s+(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm);
  for (const match of direct) names.push(match[1]);
  const lists = source.matchAll(/^export\s*\{([^}]*)\}\s*;/gm);
  for (const match of lists) {
    for (const piece of match[1].split(',')) {
      const name = piece.trim().split(/\s+as\s+/).pop();
      if (name) names.push(name);
    }
  }
  return [...new Set(names)];
}

function topLevelNames(stripped) {
  const names = [];
  const matches = stripped.matchAll(/^(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm);
  for (const match of matches) names.push(match[1]);
  return names;
}

if (process.argv[1] && process.argv[1].endsWith('build-embedded.js')) {
  const { htmlPath, html, changed, bundle } = render();
  writeFileSync(htmlPath, html);
  console.log(`${changed ? 'updated' : 'already up to date'}: ${htmlPath} (${SOURCES.length} files, ${bundle.split('\n').length} lines)`);
}
